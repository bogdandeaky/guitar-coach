class LearningProgress {
  constructor(profile) {
    this.profile = profile;
    this.completed = [];
    this.load();
  }

  get key() {
    return `guitar-progress-${this.profile}`;
  }

  load() {
    try {
      const saved = JSON.parse(localStorage.getItem(this.key) || '{}');
      this.completed = Array.isArray(saved.completed) ? [...new Set(saved.completed.filter(id => LEARNING_PATH.some(lesson => lesson.id === id)))] : [];
    } catch {
      this.completed = [];
    }
  }

  save() {
    localStorage.setItem(this.key, JSON.stringify({ completed: this.completed }));
  }

  complete(id) {
    if (!LEARNING_PATH.some(lesson => lesson.id === id)) return;
    if (!this.completed.includes(id)) this.completed.push(id);
    this.save();
  }

  nextLesson() {
    return LEARNING_PATH.find(lesson => !this.completed.includes(lesson.id)) || LEARNING_PATH[0];
  }

  songsUnlocked() {
    return this.completed.includes('familiar-phrase');
  }
}

